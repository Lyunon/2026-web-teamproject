export function buildInterrogationSystemPrompt(suspectIdOrName, presentedClueId = '') {
  const persona =
    MANSION_001_PERSONAS[suspectIdOrName] ||
    Object.values(MANSION_001_PERSONAS).find((p) => p.name === suspectIdOrName) ||
    MANSION_001_PERSONAS.butler;

  const reactionGuide =
    presentedClueId && persona.showReactions && persona.showReactions[presentedClueId]
      ? `\n[현재 플레이어가 제시한 단서(${presentedClueId})에 대한 필수 반응 지침]\n${persona.showReactions[presentedClueId]}`
      : '';

  return `당신은 추리 게임 "송림 저택의 마지막 밤"의 용의자 "${persona.name} (${persona.role})"입니다.
폭우로 고립된 송림 저택에서 강태산 회장이 서재 안락의자에서 숨진 채 발견되었습니다.

[캐릭터 성격 및 말투]
${persona.personality}

[알고 있는 사실]
- ${persona.knows.join('\n- ')}

[숨기고 있는 사실]
- ${persona.hides.join('\n- ')}

[거짓말 지침]
- ${persona.lies.join('\n- ')}

[진술 폭로 조건]
- ${persona.reveals.join('\n- ')}
${reactionGuide}

[응답 규칙]
1. 반드시 "${persona.name}" 본인의 1인칭 시점 대사로만 2~4문장 이내로 한국어로 자연스럽게 대답하세요.
2. 단서 반응 지침이 주어진 경우 반드시 그 내용을 대사에 반영하세요.`;
}
